"""Generates user_classes.py from v3_reference.py by exact text patches, so every class cell stays verbatim except the
single permitted change: a `normalizer` switch in MultiHeadAttention. Each patch must match exactly once or this script fails.

    python _make_user_classes.py        # rewrites user_classes.py next to this file
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = (HERE / "v3_reference.py").read_text(encoding="utf-8")

PATCHES = [
    # 1) constructor: one new keyword, stored as a plain attribute (no parameter, no buffer -> state_dict and RNG stream are unchanged)
    ("  def __init__(self, embed_dim, num_heads, dropout=0.1):\n    super().__init__()\n\n    self.head_dim = embed_dim // num_heads\n",
     "  def __init__(self, embed_dim, num_heads, dropout=0.1, normalizer=\"softmax\"):\n    super().__init__()\n\n"
     "    # v4: the ONE permitted change. \"softmax\" is the untouched v3 path; \"sigmoid\" is PDF Part D.\n"
     "    self.normalizer = normalizer\n\n    self.head_dim = embed_dim // num_heads\n"),
    # 2) forward: the normaliser itself
    ("    attention_weights = self.sf(attention_inside)\n    self.attention_weights = attention_weights\n",
     "    if self.normalizer == \"softmax\":\n"
     "      attention_weights = self.sf(attention_inside)\n"
     "    elif self.normalizer == \"sigmoid\":\n"
     "      # a_tj = sigmoid(z_tj - log T_t), T_t = number of visible keys of query t. No renormalisation afterwards.\n"
     "      # Masked keys have z = -inf -> weight exactly 0. attention_logits above stays the raw z (same quantity in both arms).\n"
     "      if mask is not None:\n"
     "        T_t = (~mask).sum(dim=-1, keepdim=True).clamp(min=1).to(attention_inside.dtype)\n"
     "      else:\n"
     "        T_t = torch.full_like(attention_inside[..., :1], float(attention_inside.shape[-1]))\n"
     "      attention_weights = torch.sigmoid(attention_inside - torch.log(T_t))\n"
     "    else:\n"
     "      raise ValueError(f\"unknown normalizer '{self.normalizer}' (softmax | sigmoid)\")\n"
     "    self.attention_weights = attention_weights\n"),
]
out = src
for old, new in PATCHES:
    assert out.count(old) == 1, f"patch target found {out.count(old)} times (expected 1):\n{old}"
    out = out.replace(old, new)

header_old = out[: out.index("import math\n")]
header_new = ('"""The class cells used by every v4 model. GENERATED by _make_user_classes.py from v3_reference.py: do not edit by hand.\n'
              'Identical to the v3 notebook cells except for the `normalizer` switch in MultiHeadAttention (two patches, marked `v4:`).\n'
              'tests.test_softmax_bitwise proves the softmax path is bit-for-bit the v3 class and that no other class differs."""\n')
out = header_new + out[len(header_old):]
(HERE / "user_classes.py").write_text(out, encoding="utf-8", newline="\n")
print("user_classes.py written:", len(out), "chars;", len(PATCHES), "patches applied")
